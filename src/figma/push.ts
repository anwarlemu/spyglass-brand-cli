// What `figma push` hands the Figma MCP tools: a small SVG as a use_figma script that imports it as editable layers
// (text as text layers once its fonts load); anything bigger, and pictures, through upload_assets (an SVG arrives as
// editable vectors); HTML through html_to_figma.

const SCRIPT_LIMIT = 45000;
/** A use_figma script that imports a small SVG as editable layers in a named frame (the SVG's ids become layer names). */
export function svgScript(svg: string, frameName: string): string | null {
	const script = `// Imports ${frameName} as editable layers. Generated by figma push; safe to rerun.
const SVG = ${JSON.stringify(svg)};
// Text in the SVG imports as text layers only when its fonts are loaded first (each family at the weights it uses).
const FONTS = ${JSON.stringify(fontsOf(svg))};
const missing = [];
for (const [family, style] of FONTS) { try { await figma.loadFontAsync({ family, style }); } catch (e) { missing.push(family + ' ' + style); } }
const old = figma.currentPage.children.find((n) => n.name === ${JSON.stringify(frameName)});
if (old) old.remove();
const node = figma.createNodeFromSvg(SVG);
node.name = ${JSON.stringify(frameName)};
const right = figma.currentPage.children.filter((n) => n !== node).reduce((m, n) => Math.max(m, n.x + n.width), 0);
node.x = right ? right + 120 : 0;
node.y = 0;
return { frameId: node.id, children: node.children.length, text: node.findAll((n) => n.type === 'TEXT').length, missingFonts: missing, createdNodeIds: [node.id], mutatedNodeIds: [] };
`;
	return script.length <= SCRIPT_LIMIT ? script : null;
}

const STYLE_OF: Record<string, string> = { '100': 'Thin', '200': 'ExtraLight', '300': 'Light', '400': 'Regular', '500': 'Medium', '600': 'SemiBold', '700': 'Bold', '800': 'ExtraBold', '900': 'Black' };

/** The [family, style] pairs a drawn SVG's text uses. */
export function fontsOf(svg: string): [string, string][] {
	const pairs = new Set<string>();
	for (const m of svg.matchAll(/<text\b[^>]*>/g)) {
		const family = /font-family="([^"]+)"/.exec(m[0])?.[1]?.split(',')[0]?.replace(/['"]/g, '').trim();
		if (!family) continue;
		const weight = /font-weight="(\d+)"/.exec(m[0])?.[1] ?? '400';
		pairs.add(JSON.stringify([family, STYLE_OF[weight] ?? 'Regular']));
	}
	return [...pairs].map((p) => JSON.parse(p) as [string, string]);
}

/** Cleans an SVG for Figma: drops the XML prolog, comments, scripts and editor metadata; keeps ids as layer names. */
export function figmaSvg(svg: string): string {
	return svg
		.replace(/<\?xml[^>]*\?>/g, '')
		.replace(/<!DOCTYPE[^>]*>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/<script[\s\S]*?<\/script>/gi, '')
		.replace(/<metadata[\s\S]*?<\/metadata>/gi, '')
		// Embedded faces: Figma sets the text in its own copy of the same Google fonts, loaded by the script.
		.replace(/<style[^>]*>\s*(?:<!\[CDATA\[)?\s*(?:@font-face\{[^}]*\}\s*)+(?:\]\]>)?\s*<\/style>/g, '')
		.replace(/\s(?:sodipodi|inkscape):[\w-]+="[^"]*"/g, '')
		.trim();
}

/** Parses a Figma URL into the file key and node id the MCP tools take. */
export function parseFigmaUrl(url: string): { fileKey: string; nodeId?: string; kind: string } {
	const m = /figma\.com\/(design|file|board|slides|make|proto)\/([0-9a-zA-Z]{10,128})(?:\/[^?]*?)?(?:\/branch\/([0-9a-zA-Z]+))?(?:[/?].*)?$/.exec(url);
	if (!m) throw new Error(`Not a Figma file URL: ${url}. Expected https://figma.com/design/<fileKey>/<name>?node-id=1-2`);
	const branch = /\/branch\/([0-9a-zA-Z]+)/.exec(url)?.[1];
	const node = /[?&]node-id=([\d]+[-:][\d]+)/.exec(url)?.[1];
	return { fileKey: branch ?? m[2]!, ...(node ? { nodeId: node.replace('-', ':') } : {}), kind: m[1] === 'file' ? 'design' : m[1]! };
}
